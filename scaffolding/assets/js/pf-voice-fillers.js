    function getRandomFiller(delayed) {
        var list = delayed ? DELAYED_FILLERS : EARLY_FILLERS;
        var index = Math.floor(Math.random() * list.length);

        if (delayed) {
            if (index === lastDelayedIndex && list.length > 1) {
                index = (index + 1) % list.length;
            }
            lastDelayedIndex = index;
        } else {
            if (index === lastEarlyIndex && list.length > 1) {
                index = (index + 1) % list.length;
            }
            lastEarlyIndex = index;
        }

        return list[index];
    }

